#!/usr/bin/env python3
"""Regenerate rosterchief/fast_suite_skip.txt: the tests `manage.py test --fast` skips.

    uv run python deploy/refresh_fast_suite.py          # ~2 minutes: runs the whole suite under coverage

It runs the full suite serially under coverage.py with one dynamic context per test, then picks
the smallest set of tests (greedily: always the test adding the most not-yet-covered lines) that
covers every line the whole suite covers. Every other test adds no line coverage of its own, and
goes in the skip file. Tests that ran no application code at all are never skipped, and neither is
any test that is not in the file -- so a newly written test always runs, even in the fast tier.

What this does NOT prove: that a skipped test asserts nothing the kept ones don't. Line coverage
says the code ran, not that each behaviour was checked, which is why the fast tier is only for
quick feedback (local runs, feature-branch CI) and releases, main and the nightly run everything.
The list is then VERIFIED: the fast tier is run under coverage and must hit every line the full
suite hit. Tests interact (a cached feature flag, test order), so a test that covers a line when run
alone-in-the-full-suite may not when the suite around it is smaller; any line the fast tier loses
gets every test that covered it restored, and the check repeats until nothing is lost.

Regenerate it now and then (and after big refactors): a stale list only makes the fast tier a
little less representative; it can never hide a test from a full run.
"""

import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

from coverage import CoverageData

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "rosterchief" / "fast_suite_skip.txt"

RCFILE = """[run]
dynamic_context = test_function
branch = False
data_file = {data}
source = .
omit =
    */migrations/*
    */tests.py
    */test_*.py
    .venv/*
    node_modules/*
    manage.py
    rosterchief/test_runner.py
    rosterchief/test_support.py
"""

HEADER = """# Tests `manage.py test --fast` skips: each adds no line coverage of its own (every line it runs is
# also run by a test that is kept). Generated by deploy/refresh_fast_suite.py -- do not edit by hand.
# Not in this file = runs in the fast tier, so a new test is never skipped until this is regenerated.
"""


def run_suite_under_coverage(workdir: Path, name: str, *extra: str) -> Path:
    data = workdir / f"{name}.db"
    rcfile = workdir / f"{name}.rc"
    rcfile.write_text(RCFILE.format(data=data))
    command = ["coverage", "run", f"--rcfile={rcfile}", "manage.py", "test", "--parallel", "1", *extra]
    print(f"Running the {'fast tier' if extra else 'whole suite'} under coverage...", flush=True)
    subprocess.run(command, cwd=ROOT, check=True)
    return data


def lines_per_test(data_file: Path) -> dict[str, set]:
    data = CoverageData(basename=str(data_file))
    data.read()
    per_test: dict[str, set] = defaultdict(set)
    for path in data.measured_files():
        for line, contexts in data.contexts_by_lineno(path).items():
            for context in contexts:
                if context:  # "" is code executed at import time, outside any test
                    per_test[context].add((path, line))
    return per_test


def smallest_covering_set(per_test: dict[str, set]) -> set:
    remaining = set().union(*per_test.values())
    chosen = set()
    while remaining:
        best = max(per_test, key=lambda test: len(per_test[test] & remaining))
        if not per_test[best] & remaining:
            break
        chosen.add(best)
        remaining -= per_test[best]
    return chosen


def write_skip_file(skipped) -> None:
    OUTPUT.write_text(HEADER + "\n".join(sorted(skipped)) + "\n")


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        workdir = Path(tmp)
        per_test = lines_per_test(run_suite_under_coverage(workdir, "full"))
        everything = set().union(*per_test.values())
        skipped = set(per_test) - smallest_covering_set(per_test)

        for attempt in range(1, 5):
            write_skip_file(skipped)
            fast_lines = set().union(*lines_per_test(run_suite_under_coverage(workdir, f"fast{attempt}", "--fast")).values())
            lost = everything - fast_lines
            print(f"Verification {attempt}: the fast tier misses {len(lost)} of {len(everything)} lines.", flush=True)
            if not lost:
                break
            # Restore EVERY skipped test that covered a lost line, not just the most useful one: a
            # test can have covered a line in the full run only because an earlier test left state
            # behind (a cached feature flag), and would not cover it again in a smaller suite. The
            # tests that really exercise the line are among them.
            skipped -= {test for test in skipped if per_test[test] & lost}
        else:
            print("Could not verify the list after 4 attempts; not trusting it.", file=sys.stderr)
            return 1

    print(f"{len(per_test)} tests ran application code; {len(per_test) - len(skipped)} are kept for the fast tier, {len(skipped)} skipped.")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
